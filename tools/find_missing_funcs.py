"""Finds functions that are only called through pointers in data and were not recompiled.

Usage:
    py tools/find_missing_funcs.py <default.bin> <generated/default/doa4_init.cpp> [--toml]

Scans the data sections (.rdata, .data) for 32-bit values pointing into the
code (.text). A value is considered a likely function start if the previous
instruction ends a function (blr, bctr, unconditional b) or is padding (0).
Prints the ones that are missing from the function table generated by
ReXGlue. Addresses that fall *inside* a .pdata function are skipped: they are
SEH handlers (__except/__finally), not functions. Switch cases must be
filtered out separately (they appear as loc_ labels in the generated code).
With --toml, prints lines ready for [entrypoint.functions] (without bounds:
the analyzer computes them).
"""
import re
import struct
import sys

from find_setjmp import pdata_functions

BASE = 0x82000000


def sections(img):
    pe = struct.unpack_from("<I", img, 0x3C)[0]
    nsec = struct.unpack_from("<H", img, pe + 6)[0]
    sec = pe + 24 + struct.unpack_from("<H", img, pe + 20)[0]
    for i in range(nsec):
        s = sec + i * 40
        name = img[s : s + 8].rstrip(b"\0").decode()
        vsize, va = struct.unpack_from("<II", img, s + 8)
        yield name, BASE + va, vsize


def ends_function(word):
    if word in (0x4E800020, 0x4E800420, 0):  # blr, bctr, padding
        return True
    return word >> 26 == 18 and not word & 1  # b (without link)


def main():
    img = open(sys.argv[1], "rb").read()
    registered = {int(m, 16) for m in re.findall(r"\{ 0x([0-9A-F]{8}), sub_", open(sys.argv[2]).read())}
    secs = {name: (start, size) for name, start, size in sections(img)}
    code_lo, code_size = secs[".text"]
    code_hi = code_lo + code_size

    pdata = list(pdata_functions(img))
    inside_pdata = lambda v: any(s < v < s + size for s, size in pdata)

    candidates = {}
    for name in (".rdata", ".data"):
        start, size = secs[name]
        for addr in range(start, start + size - 3, 4):
            v = struct.unpack_from(">I", img, addr - BASE)[0]
            if code_lo < v < code_hi and v % 4 == 0 and v not in registered:
                prev = struct.unpack_from(">I", img, v - 4 - BASE)[0]
                first = struct.unpack_from(">I", img, v - BASE)[0]
                if ends_function(prev) and first != 0 and not inside_pdata(v):
                    candidates.setdefault(v, []).append(addr)

    for target, refs in sorted(candidates.items()):
        if "--toml" in sys.argv:
            print(f"0x{target:08X} = {{}}  # referenced from {', '.join(f'0x{r:08X}' for r in refs[:3])}")
        else:
            print(f"{target:#010x}  riferimenti: {', '.join(hex(r) for r in refs[:4])}")
    print(f"# candidates: {len(candidates)}", file=sys.stderr)


if __name__ == "__main__":
    main()
